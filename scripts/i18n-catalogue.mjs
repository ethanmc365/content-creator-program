#!/usr/bin/env node
// EVERY STRING THE PRODUCT SAYS, AND WHICH SCREEN SAYS IT.
//
// The dictionary is keyed on the English sentence (see src/lib/i18n.js), which
// is the right trade for developers and a bad one for a translator: a flat list
// of 1,300 sentences in no order is not something a Spanish market manager can
// work through. Ethan: "would it just show all the copy? Like, you could click
// on the pages, see all the copy there, and just properly translate them rather
// than actually going through the platform."
//
// So this writes the answer at BUILD time, from the same scan the report does:
// a map of English source -> the screens that say it. The editor
// (/admin/languages) reads it and groups by screen, so "the Challenges page"
// is a list you can finish rather than a search you have to guess at.
//
// GENERATED, NOT MAINTAINED. It is regenerated by `prebuild`, so it cannot go
// stale in a way anybody has to notice - a string that moves to another file
// moves here on the next deploy.
//
//   node scripts/i18n-catalogue.mjs

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, basename } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const SRC = join(ROOT, 'src')
const OUT = join(SRC, 'locales/catalogue.json')

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name)
    if (statSync(full).isDirectory()) walk(full, out)
    else if (/\.jsx?$/.test(name) && !/\.test\./.test(name)) out.push(full)
  }
  return out
}

// Same matcher as the report: `tr('...')` on one line, single or double quoted.
// A template literal cannot be a key - the whole point of the placeholder API
// is that the sentence is not built at the call site.
const CALL = /\btr\(\s*(['"])((?:\\.|(?!\1)[^\\])*)\1/g

// WHICH SCREEN A FILE IS. The path is the only thing that knows, and the shape
// of this repository makes it readable: a page is a screen, a component under
// `components/` is shared furniture, and anything under `admin/` is the team's.
// Spelling it out beats a hand-kept table that would drift the week somebody
// renames a file.
function areaFor(rel) {
  const name = basename(rel).replace(/\.jsx?$/, '')
  const spaced = name.replace(/([a-z0-9])([A-Z])/g, '$1 $2')
  if (rel.includes('/pages/admin/')) return `Admin · ${spaced}`
  if (rel.includes('/pages/legal/')) return `Legal · ${spaced}`
  if (rel.includes('/pages/auth/')) return `Signing in · ${spaced}`
  if (rel.includes('/pages/')) return spaced
  if (rel.includes('/components/admin/')) return `Admin · ${spaced}`
  if (rel.includes('/components/')) return `Shared · ${spaced}`
  return `Other · ${spaced}`
}

const byArea = {}
for (const file of walk(SRC)) {
  const rel = relative(ROOT, file)
  if (rel.includes('/locales/')) continue
  // Comments are stripped first: this codebase's notes quote `tr('...')` as an
  // example in several places, and those are not copy.
  const src = readFileSync(file, 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/.*$/gm, '')
  const area = areaFor(rel)
  for (const m of src.matchAll(CALL)) {
    const key = m[2].replace(/\\'/g, "'").replace(/\\"/g, '"')
    ;(byArea[area] ||= new Set()).add(key)
  }
}

const out = {}
for (const area of Object.keys(byArea).sort()) out[area] = [...byArea[area]].sort()

writeFileSync(OUT, `${JSON.stringify(out, null, 0)}\n`)
const strings = new Set(Object.values(out).flat())
console.log(`  ${strings.size} strings across ${Object.keys(out).length} screens → ${relative(ROOT, OUT)}`)
