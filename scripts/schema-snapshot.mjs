#!/usr/bin/env node
//
// Write a readable snapshot of the live database schema into supabase/schema/.
//
// WHY: supabase/migrations/ is history, not a description of production. Some
// objects were created by hand-applied SQL and several functions were rewritten
// many times, so "what is live right now" cannot be read from the migrations.
// This reads it straight off the server, one file per kind of object, so a
// developer (or a move to another Postgres) starts from what actually runs.
//
// It needs only a Supabase ACCOUNT token (no database password):
//
//   SUPABASE_ACCESS_TOKEN=sbp_... node scripts/schema-snapshot.mjs
//   PROJECT_REF=<ref> OUT=supabase/schema node scripts/schema-snapshot.mjs
//
// On this Mac the token lives in the keychain:
//   SUPABASE_ACCESS_TOKEN="$(security find-generic-password -a "$USER" -s supabase-access-token -w)"
//
// It is read-only: every statement it sends is a SELECT over the catalogs.
// Re-run it after a migration and commit the diff.
//
// For a byte-exact, restorable dump use pg_dump against the database itself
// (`pg_dump --schema-only --schema=public`); this snapshot is the readable map.

import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const REF = process.env.PROJECT_REF || 'heuhqqoxyggawuckxocp'
const OUT = process.env.OUT || 'supabase/schema'
const TOKEN = process.env.SUPABASE_ACCESS_TOKEN
if (!TOKEN) {
  console.error('Set SUPABASE_ACCESS_TOKEN (a Supabase account token, sbp_...).')
  process.exit(1)
}

async function sql(query) {
  const res = await fetch(`https://api.supabase.com/v1/projects/${REF}/database/query`, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${TOKEN}`,
      'Content-Type': 'application/json',
      // Cloudflare in front of the Management API refuses an empty user agent.
      'User-Agent': 'tryp-schema-snapshot',
    },
    body: JSON.stringify({ query }),
  })
  const body = await res.json()
  if (!res.ok || !Array.isArray(body)) throw new Error(`query failed (${res.status}): ${JSON.stringify(body).slice(0, 400)}`)
  return body
}

// Objects that belong to an extension (pg_net, pg_cron...) are not ours to describe.
const NOT_EXTENSION = (oid) => `not exists (select 1 from pg_depend d where d.objid = ${oid} and d.deptype = 'e')`

const header = (title) =>
  `-- ${title}\n-- Generated by scripts/schema-snapshot.mjs from project ${REF}. Do not edit by hand.\n\n`

async function tables() {
  const cols = await sql(`
    select c.relname as table, a.attname as col, format_type(a.atttypid, a.atttypmod) as type,
           a.attnotnull as notnull, pg_get_expr(ad.adbin, ad.adrelid) as def, a.attidentity as ident,
           a.attgenerated as gen, col_description(c.oid, a.attnum) as comment
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
      join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
      left join pg_attrdef ad on ad.adrelid = c.oid and ad.adnum = a.attnum
     where n.nspname = 'public' and c.relkind in ('r', 'p')
     order by c.relname, a.attnum`)
  const cons = await sql(`
    select c.relname as table, k.conname as name, pg_get_constraintdef(k.oid) as def, k.contype as type
      from pg_constraint k join pg_class c on c.oid = k.conrelid join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' order by c.relname, k.contype, k.conname`)
  const meta = await sql(`
    select c.relname as table, c.relrowsecurity as rls, c.relforcerowsecurity as force_rls,
           obj_description(c.oid, 'pg_class') as comment
      from pg_class c join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' and c.relkind in ('r', 'p') order by 1`)

  let out = header('Tables in public: columns, constraints, row level security')
  for (const t of meta) {
    if (t.comment) out += `-- ${t.comment.replace(/\n/g, '\n-- ')}\n`
    const lines = cols.filter((c) => c.table === t.table).map((c) => {
      let l = `  ${q(c.col)} ${c.type}`
      if (c.gen === 's') l += ` generated always as (${c.def}) stored`
      else if (c.ident) l += ` generated ${c.ident === 'a' ? 'always' : 'by default'} as identity`
      else if (c.def) l += ` default ${c.def}`
      if (c.notnull) l += ' not null'
      return l
    })
    for (const k of cons.filter((k) => k.table === t.table)) lines.push(`  constraint ${q(k.name)} ${k.def}`)
    out += `create table public.${q(t.table)} (\n${lines.join(',\n')}\n);\n`
    if (t.rls) out += `alter table public.${q(t.table)} enable row level security;\n`
    if (t.force_rls) out += `alter table public.${q(t.table)} force row level security;\n`
    for (const c of cols.filter((c) => c.table === t.table && c.comment)) {
      out += `comment on column public.${q(t.table)}.${q(c.col)} is ${lit(c.comment)};\n`
    }
    out += '\n'
  }
  return out
}

async function indexes() {
  const rows = await sql(`
    select i.indexrelid::regclass::text as name, pg_get_indexdef(i.indexrelid) as def
      from pg_index i join pg_class c on c.oid = i.indrelid join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public'
       and not exists (select 1 from pg_constraint k where k.conindid = i.indexrelid)
     order by c.relname, 1`)
  return header('Indexes in public (those behind primary keys and unique constraints are in tables.sql)') +
    rows.map((r) => `${r.def};`).join('\n') + '\n'
}

async function views() {
  const rows = await sql(`
    select c.relname as name, c.relkind as kind, pg_get_viewdef(c.oid, true) as def,
           c.reloptions::text as opts
      from pg_class c join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' and c.relkind in ('v', 'm') order by 1`)
  return header('Views and materialized views in public') + rows.map((r) =>
    r.kind === 'm'
      ? `create materialized view public.${q(r.name)} as\n${r.def}\n`
      : `create or replace view public.${q(r.name)}${r.opts ? ` with (${r.opts.replace(/[{}"]/g, '')})` : ''} as\n${r.def}\n`,
  ).join('\n')
}

async function functions() {
  const rows = await sql(`
    select p.proname as name, pg_get_function_identity_arguments(p.oid) as args,
           pg_get_functiondef(p.oid) as def, p.prosecdef as definer,
           coalesce((select string_agg(distinct r.rolname, ', ' order by r.rolname)
                       from aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
                       join pg_roles r on r.oid = a.grantee
                      where a.privilege_type = 'EXECUTE' and r.rolname in ('anon', 'authenticated', 'service_role')
                    ), '') as callers,
           exists (select 1 from aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
                    where a.privilege_type = 'EXECUTE' and a.grantee = 0) as public_exec
      from pg_proc p
     where p.pronamespace = 'public'::regnamespace and p.prokind in ('f', 'p') and ${NOT_EXTENSION('p.oid')}
     order by 1, 2`)
  const byName = new Map()
  for (const r of rows) {
    if (!byName.has(r.name)) byName.set(r.name, [])
    byName.get(r.name).push(r)
  }
  const files = {}
  for (const [name, defs] of byName) {
    files[`${name}.sql`] = header(`public.${name}`) + defs.map((r) => {
      const callers = r.public_exec ? 'PUBLIC (everyone)' : r.callers || 'owner only (no API role)'
      return `-- ${r.definer ? 'SECURITY DEFINER' : 'security invoker'}; API roles that may call it: ${callers}\n${r.def.trim()};\n`
    }).join('\n')
  }
  const index = header(`Every function in public (${rows.length}), one file per name under functions/`) +
    [...byName.keys()].map((n) => `-- functions/${n}.sql`).join('\n') + '\n'
  return { files, index }
}

async function triggers() {
  const rows = await sql(`
    select c.relname as table, t.tgname as name, pg_get_triggerdef(t.oid, true) as def, t.tgenabled as enabled
      from pg_trigger t join pg_class c on c.oid = t.tgrelid join pg_namespace n on n.oid = c.relnamespace
     where not t.tgisinternal and n.nspname in ('public', 'storage', 'auth')
     order by n.nspname, c.relname, t.tgname`)
  const ev = await sql(`select evtname, evtevent, evtfoid::regproc::text as fn, evttags::text as tags, evtenabled from pg_event_trigger order by 1`)
  return header('Triggers on public/auth/storage tables, then event triggers') +
    rows.map((r) => `${r.def};${r.enabled === 'D' ? ' -- DISABLED' : ''}`).join('\n') +
    '\n\n-- Event triggers (fire on DDL, not on rows)\n' +
    ev.map((e) => `-- ${e.evtname}: on ${e.evtevent}${e.tags ? ` ${e.tags}` : ''} -> ${e.fn}${e.evtenabled === 'D' ? ' (disabled)' : ''}`).join('\n') + '\n'
}

async function policies() {
  const rows = await sql(`
    select schemaname, tablename, policyname, permissive, roles::text as roles, cmd, qual, with_check
      from pg_policies where schemaname in ('public', 'storage') order by 1, 2, 3`)
  return header('Row level security policies (public and storage)') + rows.map((p) => {
    let s = `create policy ${q(p.policyname)} on ${p.schemaname}.${q(p.tablename)}\n  as ${p.permissive.toLowerCase()} for ${p.cmd.toLowerCase()} to ${p.roles.replace(/[{}]/g, '')}`
    if (p.qual) s += `\n  using (${p.qual})`
    if (p.with_check) s += `\n  with check (${p.with_check})`
    return s + ';\n'
  }).join('\n')
}

async function platform() {
  const ext = await sql(`select extname, extversion, extnamespace::regnamespace::text as schema from pg_extension order by 1`)
  const types = await sql(`
    select t.typname as name, string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) as labels
      from pg_type t join pg_enum e on e.enumtypid = t.oid where t.typnamespace = 'public'::regnamespace group by 1 order by 1`)
  const cron = await sql(`select jobname, schedule, command, active from cron.job order by jobname`)
  const pub = await sql(`select tablename from pg_publication_tables where pubname = 'supabase_realtime' order by 1`)
  const buckets = await sql(`select id, public, file_size_limit, allowed_mime_types::text as mimes from storage.buckets order by 1`)
  let out = header('Extensions, enum types, scheduled jobs, realtime publication, storage buckets')
  out += '-- Extensions\n' + ext.map((e) => `--   ${e.extname} ${e.extversion} (schema ${e.schema})`).join('\n') + '\n\n'
  out += '-- Enum types\n' + (types.map((t) => `create type public.${q(t.name)} as enum (${t.labels});`).join('\n') || '-- (none)') + '\n\n'
  out += '-- pg_cron jobs (schedule is UTC)\n' + cron.map((j) =>
    `select cron.schedule(${lit(j.jobname)}, ${lit(j.schedule)}, ${lit(j.command.trim())});${j.active ? '' : ' -- INACTIVE'}`).join('\n') + '\n\n'
  out += '-- Tables in the supabase_realtime publication (clients can subscribe to their changes)\n' +
    pub.map((p) => `--   ${p.tablename}`).join('\n') + '\n\n'
  out += '-- Storage buckets\n' + buckets.map((b) =>
    `--   ${b.id}: ${b.public ? 'public' : 'PRIVATE'}, limit ${b.file_size_limit ?? 'none'}, types ${b.mimes ?? 'any'}`).join('\n') + '\n'
  return out
}

function q(ident) {
  return /^[a-z_][a-z0-9_]*$/.test(ident) ? ident : `"${ident.replace(/"/g, '""')}"`
}
function lit(s) {
  return `'${String(s).replace(/'/g, "''")}'`
}

const fns = await functions()
rmSync(OUT, { recursive: true, force: true })
mkdirSync(join(OUT, 'functions'), { recursive: true })
writeFileSync(join(OUT, 'tables.sql'), await tables())
writeFileSync(join(OUT, 'indexes.sql'), await indexes())
writeFileSync(join(OUT, 'views.sql'), await views())
writeFileSync(join(OUT, 'triggers.sql'), await triggers())
writeFileSync(join(OUT, 'policies.sql'), await policies())
writeFileSync(join(OUT, 'platform.sql'), await platform())
writeFileSync(join(OUT, 'functions.sql'), fns.index)
for (const [file, body] of Object.entries(fns.files)) writeFileSync(join(OUT, 'functions', file), body)
console.log(`Wrote ${OUT}: ${Object.keys(fns.files).length} function files + tables, indexes, views, triggers, policies, platform.`)
