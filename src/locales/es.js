// Keyed on the English source sentence - see lib/i18n.js for why there are no
// invented keys anywhere in this file, and why a string that is missing here
// simply renders in English rather than breaking a screen.
//
// THE DECISIONS THIS TRANSLATION MAKES, written down so the next language and
// the next contributor follow the same ones rather than each inventing their
// own. A product that says "reto" on one screen and "desafío" on the next reads
// as two products.
//
//  * TÚ, NEVER USTED. This is a community of creators talking to each other,
//    and the English is already informal ("Nothing here yet", "Give it another
//    try"). `usted` would make the same sentences sound like a bank.
//  * SPAIN, NOT NEUTRAL LATIN AMERICAN. Spain is the market that is running,
//    so: "Ajustes" rather than "Configuración", "móvil" rather than "celular",
//    "vídeo" with the accent, "ordenador" rather than "computadora".
//  * THE GLOSSARY, fixed:
//      challenge      -> reto            (shorter and more idiomatic than
//                                         "desafío" for a brief you enter)
//      market         -> mercado         (what the business calls a country
//                                         community; kept for consistency)
//      room           -> sala
//      DMs            -> Mensajes        (direct messages -> mensajes directos)
//      leaderboard    -> clasificación
//      views          -> visualizaciones (what TikTok and Instagram say in
//                                         Spain; "reproducciones" is video
//                                         playbacks, which is not the metric)
//      entry/submission -> participación
//      prize          -> premio
//      reward         -> recompensa
//      streak         -> racha
//      flight log     -> registro de vuelos
//      settings       -> ajustes
//      creator        -> creador         (generic; adjectives are kept neutral
//                                         where Spanish allows it, and no
//                                         "creador/a" slashes, which read badly
//                                         inside a sentence)
//  * NO CALQUES. "Log in" is "Iniciar sesión", not "loguearse". "Share" is
//    "Compartir". "Post" (a video) is "publicar", not "postear".
//  * SENTENCE CASE, like the English. Spanish does not capitalise every word in
//    a heading and the English here does not either.
//  * INVERTED PUNCTUATION IS NOT OPTIONAL: ¿ and ¡ open every question and
//    exclamation.
//  * LENGTH. Spanish runs roughly 20% longer than English. Where a string sits
//    in a fixed-width control - a tab label, a button in a row of three, a
//    chip - the translation is deliberately as short as the English or shorter,
//    even when a longer phrase would be more elegant. Those are marked below.

